// Regenerates usStatesMap.js from us-atlas topojson data. Run with:
//   node scripts/generate-us-states-map.js
// Requires the devDependencies us-atlas / topojson-client / d3-geo (not
// needed at runtime — only to rebuild the static path data below).
const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const { geoPath } = require('d3-geo');
const us = require('us-atlas/states-albers-10m.json');

const geojson = topojson.feature(us, us.objects.states);
const svgPath = geoPath(); // no projection arg: states-albers-10m is pre-projected

const features = geojson.features
  // Drop DC — the app tracks "50 states visited", and DC is a rounding error
  // at this map scale anyway (its shape is retained implicitly as blank space).
  .filter((f) => f.properties.name !== 'District of Columbia')
  .map((f) => ({ name: f.properties.name, d: svgPath(f) }))
  .sort((a, b) => a.name.localeCompare(b.name));

const out = `// AUTO-GENERATED by scripts/generate-us-states-map.js — do not edit by hand.
// Source: us-atlas (ISC license — https://github.com/topojson/us-atlas), derived
// from the US Census Bureau's public-domain cartographic state boundaries,
// pre-projected via d3.geoAlbersUsa to a 975x610 viewBox.
// Regenerate with: node scripts/generate-us-states-map.js

export const US_STATES_VIEWBOX = '0 0 975 610';

export const US_STATES_PATHS = ${JSON.stringify(features, null, 2)};
`;

fs.writeFileSync(path.join(__dirname, '..', 'usStatesMap.js'), out);
console.log(`Wrote ${features.length} states to usStatesMap.js`);
